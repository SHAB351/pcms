-- =============================================================================
-- 0003 — Assistant IA : opérations, confidentialité, historique des brouillons
--
-- La table `public.ai_drafts` existe depuis 0001 avec ses politiques RLS. Cette
-- migration ne les remplace pas : elle ajoute ce que l'assistant doit savoir
-- pour être honnête (quelle opération, sur quelle source, ce qui a quitté le
-- poste) et l'historique versionné des brouillons.
--
-- À exécuter dans le SQL Editor du tableau de bord Supabase, comme 0001 et
-- 0002. Ne pas lancer `supabase db push` sans réconcilier l'historique.
-- =============================================================================

-- --- 1. Ce que l'assistant doit consigner ------------------------------------

alter table public.ai_drafts
  add column if not exists operation text not null default 'redaction',
  add column if not exists source_text text,
  add column if not exists document_id uuid references public.documents (id) on delete set null,
  add column if not exists target_language text,
  add column if not exists external_sent boolean not null default false,
  add column if not exists warnings jsonb not null default '[]'::jsonb;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'ai_drafts_operation_valide'
  ) then
    alter table public.ai_drafts
      add constraint ai_drafts_operation_valide check (
        operation in ('correction', 'amelioration', 'reformulation', 'resume', 'traduction', 'redaction')
      );
  end if;
end $$;

comment on column public.ai_drafts.operation is
  'Opération demandée : correction, amelioration, reformulation, resume, traduction ou redaction.';
comment on column public.ai_drafts.external_sent is
  'Vrai seulement si le contenu a quitté le poste vers un service externe, avec autorisation.';
comment on column public.ai_drafts.document_id is
  'Document source lorsque le brouillon résume un document du module Documents.';

create index if not exists ai_drafts_document_idx on public.ai_drafts (document_id);

-- --- 2. Historique versionné -------------------------------------------------
-- Chaque version du texte est conservée. L'écriture passe uniquement par le
-- déclencheur ci-dessous : aucune politique d'insertion n'est créée, donc une
-- écriture directe est refusée par RLS.

create table if not exists public.ai_draft_revisions (
  id          bigint generated by default as identity primary key,
  draft_id    uuid not null references public.ai_drafts (id) on delete cascade,
  content     text not null,
  status      public.ai_draft_status not null,
  external_sent boolean not null default false,
  author_id   uuid references auth.users (id) on delete set null,
  created_at  timestamptz not null default now()
);

comment on table public.ai_draft_revisions is
  'Historique en ajout seul des brouillons de l''assistant. Écrit par déclencheur uniquement.';

create index if not exists ai_draft_revisions_draft_idx
  on public.ai_draft_revisions (draft_id, created_at desc);

create or replace function public.record_ai_draft_revision()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.ai_draft_revisions (draft_id, content, status, external_sent, author_id)
  values (new.id, new.content, new.status, new.external_sent, auth.uid());
  return null;
end $$;

revoke all on function public.record_ai_draft_revision() from public;

drop trigger if exists ai_drafts_record_revision on public.ai_drafts;
create trigger ai_drafts_record_revision
  after insert or update of content, status on public.ai_drafts
  for each row execute function public.record_ai_draft_revision();

alter table public.ai_draft_revisions enable row level security;

-- Lecture alignée sur celle du brouillon : l'auteur, ou tout rédacteur.
drop policy if exists "ai_revisions_select_visible" on public.ai_draft_revisions;
create policy "ai_revisions_select_visible"
  on public.ai_draft_revisions for select to authenticated
  using (
    exists (
      select 1 from public.ai_drafts d
      where d.id = ai_draft_revisions.draft_id
        and (d.created_by = auth.uid() or public.can_write())
    )
  );

-- --- 3. Seul un administrateur valide ou rejette -----------------------------
-- La politique `ai_drafts_update_author_or_admin` autorise l'auteur à modifier
-- sa ligne : sans ce garde-fou, il pourrait s'auto-attribuer une validation par
-- un appel direct à l'API REST. La validation est un acte de relecture, pas une
-- case à cocher par l'auteur.

create or replace function public.guard_ai_draft_review()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status in ('approuve', 'rejete')
     and (tg_op = 'INSERT' or old.status is distinct from new.status) then
    if not public.is_admin() then
      raise exception 'Seul un administrateur peut approuver ou rejeter un brouillon.';
    end if;
    new.reviewed_by := auth.uid();
    new.reviewed_at := now();
  end if;
  return new;
end $$;

revoke all on function public.guard_ai_draft_review() from public;

drop trigger if exists ai_drafts_guard_review on public.ai_drafts;
create trigger ai_drafts_guard_review
  before insert or update on public.ai_drafts
  for each row execute function public.guard_ai_draft_review();

-- --- 4. Une validation humaine ne survit pas à une retouche ------------------
-- Si le texte approuvé est modifié, il redevient un brouillon non relu. Ce
-- déclencheur garantit la règle même pour un appel direct à l'API REST : la
-- discipline de l'interface ne suffit pas.

create or replace function public.reset_ai_draft_on_content_change()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.content is distinct from old.content and old.status = 'approuve' then
    new.status := 'brouillon';
    new.reviewed_by := null;
    new.reviewed_at := null;
  end if;
  return new;
end $$;

drop trigger if exists ai_drafts_reset_on_content_change on public.ai_drafts;
create trigger ai_drafts_reset_on_content_change
  before update on public.ai_drafts
  for each row execute function public.reset_ai_draft_on_content_change();

-- Cohérence de la relecture : approuvé ou rejeté exige un relecteur et une date.
-- NOT VALID : les lignes existantes ne sont pas réexaminées, les écritures
-- suivantes le sont.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'ai_drafts_relecture_coherente'
  ) then
    alter table public.ai_drafts
      add constraint ai_drafts_relecture_coherente check (
        (status in ('approuve', 'rejete') and reviewed_by is not null and reviewed_at is not null)
        or (status not in ('approuve', 'rejete'))
      ) not valid;
  end if;
end $$;

